def bullet(t):
    return para("–  " + t, align="justify", after=40)


def code_file(rel):
    para("Файл " + os.path.basename(rel), size=12, bold=True, after=80, keep_next=True)
    code(open(os.path.join(ROOT, rel), encoding="utf-8").read())


def code(src):
    lines = src.rstrip("\n").split("\n")
    for i, ln in enumerate(lines):
        p = para(ln if ln else " ", size=9, font="Consolas", after=0, line=240,
                 keep_next=(i < 3))
        # лёгкая заливка блока кода
        pPr = p._p.get_or_add_pPr()
        shd = OxmlElement("w:shd")
        shd.set(qn("w:val"), "clear")
        shd.set(qn("w:color"), "auto")
        shd.set(qn("w:fill"), "F5F5F5")
        pPr.find(qn("w:spacing")).addprevious(shd)   # порядок элементов по схеме OOXML
    para("", after=60)


fig_no = [0]
tab_no = [0]


LABELS = {}


def figure(fname, caption, width=TEXT_W, label=None):
    p = para("", align="center", after=60, keep_next=True)
    p.add_run().add_picture(os.path.join(IMG, fname), width=Inches(width))
    fig_no[0] += 1
    if label:
        LABELS["F:" + label] = fig_no[0]
    para(f"Рисунок {fig_no[0]} – {caption}", size=10, italic=True,
         align="center", after=200, line=None)
    return fig_no[0]


def _borders(tbl):
    tblPr = tbl._tbl.tblPr
    b = OxmlElement("w:tblBorders")
    anchor = tblPr.find(qn("w:tblLayout"))
    if anchor is None:
        anchor = tblPr.find(qn("w:tblLook"))
    for side in ("top", "left", "bottom", "right", "insideH", "insideV"):
        e = OxmlElement(f"w:{side}")
        e.set(qn("w:val"), "single")
        e.set(qn("w:sz"), "4")
        e.set(qn("w:color"), "auto")
        b.append(e)
    if anchor is not None:
        anchor.addprevious(b)
    else:
        tblPr.append(b)


def table(rows, caption, widths=None, header_rows=1, size=11, align_cols=None,
          mono_cols=(), label=None):
    tab_no[0] += 1
    if label:
        LABELS["T:" + label] = tab_no[0]
    para(f"Таблица {tab_no[0]} – {caption}", italic=True, after=80, keep_next=True)
    ncol = len(rows[0])
    t = doc.add_table(rows=len(rows), cols=ncol)
    _append(t._tbl)
    t.alignment = 1  # по центру
    _borders(t)
    total = sum(widths) if widths else ncol
    for ri, row in enumerate(rows):
        tr = t.rows[ri]
        if ri < header_rows:
            trPr = tr._tr.get_or_add_trPr()
            trPr.append(OxmlElement("w:tblHeader"))
        for ci, val in enumerate(row):
            cell = tr.cells[ci]
            if widths:
                cell.width = Inches(TEXT_W * widths[ci] / total)
            tcPr = cell._tc.get_or_add_tcPr()
            if ri < header_rows:
                shd = OxmlElement("w:shd")
                shd.set(qn("w:val"), "clear")
                shd.set(qn("w:fill"), "D9D9D9")
                tcPr.append(shd)
            va = OxmlElement("w:vAlign")
            va.set(qn("w:val"), "center")
            tcPr.append(va)
            p = cell.paragraphs[0]
            a = (align_cols[ci] if align_cols else "center")
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER if a == "center" else WD_ALIGN_PARAGRAPH.LEFT
            p.paragraph_format.space_after = Pt(0)
            bold = False
            s = str(val)
            if s.startswith("**") and s.endswith("**"):
                s, bold = s[2:-2], True
            font = "Consolas" if (ci in mono_cols and ri >= header_rows) else "Times New Roman"
            r = p.add_run(s)
            r.font.name = font
            r._r.get_or_add_rPr().get_or_add_rFonts().set(qn("w:eastAsia"), font)
            r.font.size = Pt(size - (1 if font == "Consolas" else 0))
            r.bold = bold or ri < header_rows
            r.italic = False
    para("", after=120)
    return tab_no[0]


def page_break():
    p = para("", after=0)
    p.add_run().add_break(docx.enum.text.WD_BREAK.PAGE)


def stat(fname):
    """Разбор отчёта Yosys stat -> {ячейка: количество} (верхний модуль)."""
    s = open(os.path.join(ROOT, "synth", fname)).read()
    top = s.split("=== ")[1]
    cells = dict(re.findall(r"^\s{5}(\S+)\s+(\d+)\s*$", top, flags=re.M))
    return {k: int(v) for k, v in cells.items()}


def sim_log(name):
    return open(os.path.join(ROOT, "build", name + ".log"), encoding="utf-8").read()


