brs = [el for el in body.iterchildren()
       if el.tag == qn("w:p") and el.findall(".//" + qn("w:br"))]
for el in brs[1:]:
    body.remove(el)


def replace_text(old, new):
    for t in body.iter(qn("w:t")):
        if t.text and old in t.text:
            t.text = t.text.replace(old, new)


